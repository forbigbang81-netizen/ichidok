// ============================================================================
// One Piece per-episode skip times
// MAL ID 21, currently 1172 episodes
//
// One Piece episodes have VARIABLE intro structures:
//   - Some start with cold open (story content before OP)
//   - Some start directly with the opening
//   - Many have a RECAP segment before the opening (this is what we skip)
//   - The opening itself is ~2:25 (145s) in most episodes
//
// Each entry: { ep: number, recapEnd?: number, opStart: number, opEnd: number }
//   - recapEnd: if the episode has a recap before the OP, this is when the recap ends
//       (the Skip Intro button appears during the recap AND the OP)
//   - opStart: when the opening starts (0 if no recap)
//   - opEnd: when the opening ends (skip to this point)
//
// For episodes not listed individually, we use the default: opStart=0, opEnd=145
// (most episodes have the OP at the very start with no recap)
// ============================================================================

interface OnePieceSkip {
  ep: number;
  recapEnd?: number;  // When recap ends (OP starts here)
  opEnd: number;      // When OP ends (skip to here)
}

