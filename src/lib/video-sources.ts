// Get the video URL for a specific anime/episode/audio combination
export function getVideoUrl(animeId: number, episode: number, audio: "sub" | "dub"): VideoSource | null {
  const source = ANIME_VIDEO_SOURCES[animeId];
  if (!source) return null;

  // If we have per-episode URLs, use those (works for both SUB and DUB if dual audio)
  if (source.episodes && source.episodes[episode]) {
    return { url: source.episodes[episode], quality: "1080p" };
  }

  if (audio === "sub" && source.sub) {
    return { url: source.sub, quality: "1080p" };
  }

  if (audio === "dub" && source.dub) {
    return { url: source.dub, quality: "1080p" };
  }

  return null;
}

// Get overridden episode count for an anime
export function getEpisodeCount(animeId: number, defaultCount: number): number {
  const source = ANIME_VIDEO_SOURCES[animeId];
  if (source?.episodeCount) return source.episodeCount;
  return defaultCount;
}

// Check if an anime has video sources
export function hasVideoSource(animeId: number): boolean {
  return !!ANIME_VIDEO_SOURCES[animeId];
}
