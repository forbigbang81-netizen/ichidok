// Video sources for specific anime.
// Maps animeId → audio → episode source info.

export interface VideoSource {
  url: string;
  quality: string;
}

// Generate AnimeToki stream URL from fileId and filename
function atStreamUrl(fileId: string, filename: string, domain: string = "drive.animetoki.com"): string {
  const b64Name = btoa(filename);
  return `https://${domain}?a=download&id=${fileId}&name=${b64Name}&mode=stream`;
}

// One Piece episode filename pattern: [AnimeSakura] One Piece - {NN} - 1080p Dual Audio Sub.mkv
function opFilename(ep: number): string {
  return `[AnimeSakura] One Piece - ${String(ep).padStart(2, "0")} - 1080p Dual Audio Sub.mkv`;
}

// Naruto episode filename pattern: [AnimeToki] Naruto - Episode {N} [1080p] .mkv
function narutoFilename(ep: number): string {
  return `[AnimeToki] Naruto - Episode ${ep} [1080p] .mkv`;
}

// Naruto Shippuden episode filename pattern
function nsFilename(ep: number): string {
  return `[AnimeToki] Naruto Shippuden - Episode ${ep} [1080p] .mkv`;
}

// Demon Slayer episode filename pattern
function dsFilename(ep: number): string {
  return `[AnimeToki] Kimetsu no Yaiba_-_${String(ep).padStart(2, "0")}_ [1080p] .mkv`;
}

// MHA episode filename pattern
function mhaFilename(ep: number): string {
  return `[AnimeToki] My Hero Academia - Episode ${ep} [1080p] .mkv`;
}


